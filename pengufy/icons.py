def pixmap(name: str, color: str, size: int = 24, dpr: float = 2.0) -> QPixmap:
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="{color}" d="{PATHS[name]}"/></svg>'
    renderer = QSvgRenderer(QByteArray(svg.encode()))
    pix = QPixmap(int(size * dpr), int(size * dpr))
    pix.fill(Qt.GlobalColor.transparent)
    p = QPainter(pix)
    renderer.render(p, QRectF(0, 0, pix.width(), pix.height()))
    p.end()
    pix.setDevicePixelRatio(dpr)
    return pix


def icon(name: str, color: str = theme.DIM, active: str = theme.TEXT, checked: str | None = theme.ACCENT,
         checked_name: str | None = None) -> QIcon:
    """Dim icon that brightens on hover and turns accent-coloured when its button is checked."""
    ic = QIcon()
    for mode, c in ((QIcon.Mode.Normal, color), (QIcon.Mode.Active, active), (QIcon.Mode.Selected, active),
                    (QIcon.Mode.Disabled, theme.LINE2)):
        ic.addPixmap(pixmap(name, c), mode, QIcon.State.Off)
        if checked:
            on = checked if mode != QIcon.Mode.Disabled else theme.LINE2
            ic.addPixmap(pixmap(checked_name or name, on), mode, QIcon.State.On)
    return ic
